/**
 * GlobalBridge service worker.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * THE GOVERNING RULE: never cache anything that belongs to one user.
 * ─────────────────────────────────────────────────────────────────────────────
 * The Cache API is origin-scoped, not user-scoped. On a shared device, anything
 * this worker stores survives sign-out and is readable by the next person to use
 * the browser. So authenticated API responses, AI conversations, messages,
 * documents and admin data are NEVER written to a cache — they are passed
 * straight through to the network.
 *
 * What is cached is only what is identical for every visitor: build assets,
 * fonts, icons, and public marketing pages.
 *
 * Hand-written rather than generated by Workbox/Serwist so the caching
 * boundaries are auditable — with a security requirement this specific, an
 * opaque generated config is a liability.
 */

const VERSION = "v1";
const STATIC_CACHE = `globalbridge-static-${VERSION}`;
const PUBLIC_CACHE = `globalbridge-public-${VERSION}`;
const IMAGE_CACHE = `globalbridge-images-${VERSION}`;
const OFFLINE_URL = "/offline";

/** Every cache this version owns. Anything else gets deleted on activate. */
const OWNED_CACHES = [STATIC_CACHE, PUBLIC_CACHE, IMAGE_CACHE];

/** Public, non-personalised routes that are safe to serve from cache. */
const PUBLIC_ROUTES = new Set([
  "/", "/about", "/pricing", "/help", "/contact", "/privacy", "/terms", OFFLINE_URL,
]);

/** Caps so caches cannot grow without bound on a long-lived install. */
const IMAGE_CACHE_MAX = 60;
const PUBLIC_CACHE_MAX = 30;

// ── install ────────────────────────────────────────────────────────────────
self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(STATIC_CACHE);
      // Only the offline page is precached. Precaching the build manifest would
      // couple this worker to Next's hashed filenames and go stale on deploy.
      await cache.addAll([OFFLINE_URL, "/favicon.svg", "/icons/icon-192.png"]);
      // Activate immediately; the update flow below controls when clients switch.
      await self.skipWaiting();
    })(),
  );
});

// ── activate ───────────────────────────────────────────────────────────────
self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names
          .filter((n) => n.startsWith("globalbridge-") && !OWNED_CACHES.includes(n))
          .map((n) => caches.delete(n)),
      );
      await self.clients.claim();
    })(),
  );
});

// ── helpers ────────────────────────────────────────────────────────────────

/** Trim a cache to its newest `max` entries (approximate LRU: insertion order). */
async function trimCache(cacheName, max) {
  const cache = await caches.open(cacheName);
  const keys = await cache.keys();
  if (keys.length <= max) return;
  await Promise.all(keys.slice(0, keys.length - max).map((k) => cache.delete(k)));
}

/**
 * Requests this worker must not touch under any circumstance.
 * Returning true means "pass straight to the network, never cache".
 */
function isNeverCacheable(url, request) {
  // Anything that carries or establishes identity.
  if (url.pathname.startsWith("/api/")) return true;
  // Firebase / Google identity endpoints.
  if (/(^|\.)(googleapis|firebaseio|firebaseapp|gstatic)\.com$/.test(url.hostname)) return true;
  // Requests carrying credentials.
  if (request.headers.has("Authorization")) return true;
  // Next.js server-action and RSC payloads are per-user and per-session.
  if (url.searchParams.has("_rsc")) return true;
  // Video is far too large to cache sensibly — hero-loop.mp4 alone is 23MB, and
  // range requests produce partial responses that break a naive cache anyway.
  if (url.pathname.startsWith("/video/")) return true;
  return false;
}

/** Immutable build output — safe to cache aggressively and forever. */
function isBuildAsset(url) {
  return url.pathname.startsWith("/_next/static/");
}

function isImage(url, request) {
  return (
    request.destination === "image" ||
    url.pathname.startsWith("/_next/image") ||
    /\.(png|jpg|jpeg|gif|webp|avif|svg|ico)$/i.test(url.pathname)
  );
}

// ── fetch ──────────────────────────────────────────────────────────────────
self.addEventListener("fetch", (event) => {
  const { request } = event;

  // Only GET is ever cacheable; mutations must always hit the network.
  if (request.method !== "GET") return;

  const url = new URL(request.url);

  // Leave cross-origin requests entirely alone.
  if (url.origin !== self.location.origin) return;

  if (isNeverCacheable(url, request)) return; // browser default: straight to network

  // 1 ── Build assets: cache-first. Filenames are content-hashed, so a hit is
  //      always correct and a miss is a genuinely new file.
  if (isBuildAsset(url)) {
    event.respondWith(
      caches.match(request).then(
        (hit) =>
          hit ||
          fetch(request).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(STATIC_CACHE).then((c) => c.put(request, copy));
            }
            return res;
          }),
      ),
    );
    return;
  }

  // 2 ── Images: stale-while-revalidate. Showing a slightly old avatar beats a
  //      blank box; the refresh lands for next time.
  if (isImage(url, request)) {
    event.respondWith(
      caches.open(IMAGE_CACHE).then(async (cache) => {
        const hit = await cache.match(request);
        const network = fetch(request)
          .then((res) => {
            if (res.ok) {
              cache.put(request, res.clone());
              trimCache(IMAGE_CACHE, IMAGE_CACHE_MAX);
            }
            return res;
          })
          .catch(() => null);
        return hit || (await network) || Response.error();
      }),
    );
    return;
  }

  // 3 ── Navigations: network-first, falling back to cache, then the offline
  //      page. Network-first matters because a stale signed-in shell served to
  //      a signed-out user is confusing and looks broken.
  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        try {
          const res = await fetch(request);
          // Only public pages are worth keeping; everything else is per-user.
          if (res.ok && PUBLIC_ROUTES.has(url.pathname)) {
            const cache = await caches.open(PUBLIC_CACHE);
            cache.put(request, res.clone());
            trimCache(PUBLIC_CACHE, PUBLIC_CACHE_MAX);
          }
          return res;
        } catch {
          const cached = await caches.match(request);
          if (cached) return cached;
          const offline = await caches.match(OFFLINE_URL);
          return offline || Response.error();
        }
      })(),
    );
    return;
  }

  // Everything else falls through to the network untouched.
});

// ── update handshake ───────────────────────────────────────────────────────
// The page asks the waiting worker to take over only when the user accepts the
// update, so a deploy never reloads someone mid-form.
self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
});

// ── push ───────────────────────────────────────────────────────────────────
self.addEventListener("push", (event) => {
  if (!event.data) return;

  let payload;
  try {
    payload = event.data.json();
  } catch {
    payload = { title: "GlobalBridge", body: event.data.text() };
  }

  const kind = payload.kind || "info";

  event.waitUntil(
    self.registration.showNotification(payload.title || "GlobalBridge", {
      body: payload.body || "",
      icon: "/icons/icon-192.png",
      badge: "/icons/icon-192.png",
      // Tagging by kind collapses repeats of the same category rather than
      // stacking twelve "new message" notifications on a locked phone.
      tag: kind,
      // …but never silently swallow a safety alert behind an existing one.
      renotify: kind === "security" || kind === "deadline",
      timestamp: payload.timestamp || Date.now(),
      // Carried through to the click handler so we can deep-link precisely.
      data: { href: payload.href || "/notifications", kind },
      requireInteraction: kind === "security",
    }),
  );
});

// ── notification click ─────────────────────────────────────────────────────
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const href = event.notification.data?.href || "/notifications";

  event.waitUntil(
    (async () => {
      const clientList = await self.clients.matchAll({
        type: "window",
        includeUncontrolled: true,
      });

      // Prefer focusing an open tab and navigating it, rather than opening a
      // second copy of the app — duplicate windows are a common and irritating
      // failure of naive notification handling.
      for (const client of clientList) {
        if (new URL(client.url).origin === self.location.origin) {
          await client.focus();
          if ("navigate" in client) {
            try {
              await client.navigate(href);
            } catch {
              /* navigation can be blocked; focus alone is still useful */
            }
          }
          return;
        }
      }

      await self.clients.openWindow(href);
    })(),
  );
});
